using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Mattiverse.Core.Catalog;
using Mattiverse.Core.Security;

namespace Mattiverse.Core.Apps;

/// <summary>Resolves the answers of the install form against the catalog's variable definitions and stores them.</summary>
public static class AppVariables
{
    private const string Alphabet = "abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";

    /// <summary>A random password that is safe in <c>.env</c> files, URLs and connection strings (letters and digits only).</summary>
    public static string GenerateSecret(int length = 24) => RandomNumberGenerator.GetString(Alphabet, length);

    /// <summary>
    /// Builds the final value of every catalog variable from the form input: the typed value, else a generated
    /// secret, else the default. Variables that are already known (an update of an installed app) are kept.
    /// </summary>
    public static Dictionary<string, string> Resolve(
        CatalogApp app,
        IReadOnlyDictionary<string, string?> input,
        IReadOnlyDictionary<string, string>? existing,
        List<string> errors)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var variable in app.Variables)
        {
            input.TryGetValue(variable.Key, out var typed);
            var value = typed?.Trim();

            if (string.IsNullOrEmpty(value) && existing is not null && existing.TryGetValue(variable.Key, out var known) && !string.IsNullOrEmpty(known))
            {
                value = known;
            }

            if (string.IsNullOrEmpty(value) && variable.Generate)
            {
                value = GenerateSecret();
            }

            if (string.IsNullOrEmpty(value))
            {
                value = variable.Default;
            }

            if (string.IsNullOrEmpty(value))
            {
                if (variable.Required)
                {
                    errors.Add($"{LabelOf(variable)} is required.");
                }

                value = string.Empty;
            }
            else if (value.Contains('\'') || value.Contains('\n') || value.Contains('\r'))
            {
                errors.Add($"{LabelOf(variable)} must not contain a single quote or a line break.");
            }
            else if (variable.Type.Equals("number", StringComparison.OrdinalIgnoreCase) && !int.TryParse(value, out _))
            {
                errors.Add($"{LabelOf(variable)} must be a number.");
            }

            result[variable.Key] = value;
        }

        return result;
    }

    private static string LabelOf(CatalogVariable variable)
        => string.IsNullOrWhiteSpace(variable.Label) ? variable.Key : variable.Label;

    /// <summary>The content of the app's <c>.env</c> file: the Mattiverse built-ins followed by the variables.</summary>
    public static string BuildEnvFile(IReadOnlyDictionary<string, string> builtIns, IReadOnlyDictionary<string, string> variables)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Mattiverse. Rewritten on every install and update.");
        foreach (var (key, value) in builtIns)
        {
            sb.Append(key).Append('=').AppendLine(Quote(value));
        }

        foreach (var (key, value) in variables)
        {
            sb.Append(key).Append('=').AppendLine(Quote(value));
        }

        return sb.ToString().ReplaceLineEndings("\n");
    }

    // Single quotes keep $, # and spaces literal in a compose .env file; values never contain a single quote (see Resolve).
    private static string Quote(string value) => "'" + value + "'";

    // ---------------------------------------------------------------- storage (secrets are protected at rest)

    public static string Serialize(CatalogApp app, IReadOnlyDictionary<string, string> values, ISecretProtector protector)
    {
        var stored = new Dictionary<string, string>();
        foreach (var (key, value) in values)
        {
            var secret = app.Variables.FirstOrDefault(v => v.Key == key)?.IsSecret ?? false;
            stored[key] = secret && !string.IsNullOrEmpty(value) ? protector.Protect(value) : value;
        }

        return JsonSerializer.Serialize(stored);
    }

    public static Dictionary<string, string> Deserialize(CatalogApp? app, string? json, ISecretProtector protector)
    {
        var values = new Dictionary<string, string>(StringComparer.Ordinal);
        if (string.IsNullOrWhiteSpace(json))
        {
            return values;
        }

        var stored = JsonSerializer.Deserialize<Dictionary<string, string>>(json) ?? new();
        foreach (var (key, value) in stored)
        {
            var secret = app?.Variables.FirstOrDefault(v => v.Key == key)?.IsSecret ?? false;
            values[key] = secret && !string.IsNullOrEmpty(value) ? TryUnprotect(protector, value) : value;
        }

        return values;
    }

    private static string TryUnprotect(ISecretProtector protector, string value)
    {
        try
        {
            return protector.Unprotect(value);
        }
        catch (CryptographicException)
        {
            // The key ring was lost: the value cannot be read any more. The app keeps running with what compose has.
            return string.Empty;
        }
    }
}

/// <summary>A line of the "credentials" card of an app.</summary>
public sealed record CredentialLine(string Label, string Value, bool Secret);

/// <summary>Builds and stores the credentials card of an installed app.</summary>
public static class AppCredentials
{
    public static List<CredentialLine> Build(CatalogApp app, IReadOnlyDictionary<string, string> variables)
        => app.Credentials
            .Select(c => new CredentialLine(c.Label, EnvSubstitution.Apply(c.Value, variables), c.Secret))
            .Where(c => !string.IsNullOrWhiteSpace(c.Value))
            .ToList();

    public static string? Serialize(IReadOnlyCollection<CredentialLine> lines, ISecretProtector protector)
    {
        if (lines.Count == 0)
        {
            return null;
        }

        var stored = lines.Select(l => new CredentialLine(l.Label, l.Secret ? protector.Protect(l.Value) : l.Value, l.Secret));
        return JsonSerializer.Serialize(stored);
    }

    public static List<CredentialLine> Deserialize(string? json, ISecretProtector protector)
    {
        if (string.IsNullOrWhiteSpace(json))
        {
            return [];
        }

        var stored = JsonSerializer.Deserialize<List<CredentialLine>>(json) ?? [];
        return stored
            .Select(l =>
            {
                if (!l.Secret)
                {
                    return l;
                }

                try
                {
                    return l with { Value = protector.Unprotect(l.Value) };
                }
                catch (CryptographicException)
                {
                    return l with { Value = "(unreadable)" };
                }
            })
            .ToList();
    }
}
